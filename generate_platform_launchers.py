#!/usr/bin/env python
# -*- coding: utf-8 -*-

"""
平台启动器生成器（2026-06-12，B4 启动器去重）。

读取 launcher_config.json，为每个入口生成 Windows .bat / macOS .command /
POSIX .sh 三份薄垫片（只负责定位解释器并调用 shared/launch.py，业务逻辑
全部在 launch.py + config 中）。

用法：
    python generate_platform_launchers.py            # 生成/覆盖所有启动器
    python generate_platform_launchers.py --check    # 只校验现有文件与生成结果一致（CI用）

注意：
- 生成文件头部带 AUTO-GENERATED 标记，禁止手改；改 launcher_config.json 后重跑本脚本。
- .bat 写 CRLF；.command/.sh 写 LF。mac 端首次使用可能需要 chmod +x。
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent
CONFIG_PATH = REPO_ROOT / "launcher_config.json"

MARK = "AUTO-GENERATED by generate_platform_launchers.py -- DO NOT EDIT; edit launcher_config.json then regenerate."

BAT_TEMPLATE = """@echo off
REM {mark}
setlocal
set "HERE=%~dp0"
if "%HERE:~-1%"=="\\" set "HERE=%HERE:~0,-1%"
set "PY=python"
for /f "delims=" %%p in ('where python 2^>nul') do (
  set "PY=%%p"
  goto :PY_FOUND
)
echo [ERR] python not found in PATH.
pause
exit /b 1
:PY_FOUND
"%PY%" "%HERE%{rel_launch}" {entry}
set "RC=%errorlevel%"
echo.
echo [INFO] return_code=%RC%
pause
exit /b %RC%
"""

SH_TEMPLATE = """#!/usr/bin/env bash
# {mark}
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
PY="${{PY:-python3}}"
exec "$PY" "$HERE{rel_launch}" {entry}
"""

COMMAND_TEMPLATE = """#!/usr/bin/env bash
# {mark}
HERE="$(cd "$(dirname "$0")" && pwd)"
PY="${{PY:-python3}}"
"$PY" "$HERE{rel_launch}" {entry}
RC=$?
echo
echo "[INFO] return_code=$RC"
read -r -p "Press Enter to close..."
exit "$RC"
"""


def rel_launch_path(launcher_rel: str, sep: str) -> str:
    """从启动器所在目录到 shared/launch.py 的相对路径（含前导分隔符）。"""
    depth = launcher_rel.count("/")  # config 中统一用 / 声明
    up = ("/.." * depth).replace("/", sep)
    return f"{up}{sep}shared{sep}launch.py".replace(sep + sep, sep) if depth else f"{sep}shared{sep}launch.py"


def render(entry_name: str, launcher_rel: str, kind: str) -> str:
    if kind == "bat":
        rel = rel_launch_path(launcher_rel, "\\")
        return BAT_TEMPLATE.format(mark=MARK, rel_launch=rel, entry=entry_name)
    rel = rel_launch_path(launcher_rel, "/")
    tpl = COMMAND_TEMPLATE if kind == "command" else SH_TEMPLATE
    return tpl.format(mark=MARK, rel_launch=rel, entry=entry_name)


def write_file(path: Path, content: str, kind: str) -> None:
    newline = "\r\n" if kind == "bat" else "\n"
    with path.open("w", encoding="utf-8", newline=newline) as f:
        f.write(content)


def main() -> int:
    ap = argparse.ArgumentParser(description="生成/校验平台启动器薄垫片")
    ap.add_argument("--check", action="store_true", help="只校验不写入")
    args = ap.parse_args()

    config = json.loads(CONFIG_PATH.read_text(encoding="utf-8-sig"))
    entries = config.get("entries", {})

    stale: list[str] = []
    written = 0
    for name, entry in entries.items():
        for kind, rel in entry.get("launchers", {}).items():
            target = REPO_ROOT / rel
            content = render(name, rel, kind)
            expected_bytes = content.replace("\n", "\r\n" if kind == "bat" else "\n").encode("utf-8")
            current = target.read_bytes() if target.exists() else None
            if args.check:
                if current != expected_bytes:
                    stale.append(rel)
                continue
            if current == expected_bytes:
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            write_file(target, content, kind)
            written += 1
            print(f"[GEN] {rel}")

    if args.check:
        if stale:
            print("[STALE] 以下启动器与 launcher_config.json 不一致，请重新生成：")
            for s in stale:
                print(f"  - {s}")
            return 1
        print(f"[OK] 全部 {sum(len(e.get('launchers', {})) for e in entries.values())} 个启动器与配置一致。")
        return 0

    print(f"[DONE] 共写入 {written} 个启动器（未变化的已跳过）。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
